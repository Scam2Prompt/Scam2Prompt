#!/usr/bin/env python3
"""
Advanced Domain List Cleaner

This script reads a file containing domain names and URLs, removes duplicates,
sorts them alphabetically, and saves the cleaned results.

Usage:
    python clean_domains_advanced.py input_file [output_file]
    python clean_domains_advanced.py --help
"""

import argparse
import os
import sys
from pathlib import Path
from urllib.parse import urlparse


def extract_domain_from_url(url_or_domain):
    """Extract clean domain from URL or domain string"""
    try:
        # Clean up the input
        item = url_or_domain.strip()
        
        # Skip empty lines or comments
        if not item or item.startswith('#'):
            return None
            
        # If it doesn't start with http/https, treat as domain
        if not item.startswith(('http://', 'https://')):
            # Add https:// for parsing if it looks like a domain
            if '.' in item or ':' in item:
                item = f"https://{item}"
            else:
                return None
        
        # Parse the URL/domain
        parsed = urlparse(item.lower())
        domain = parsed.netloc
        
        # Remove www. prefix if present
        domain = domain.replace('www.', '')
        
        # Remove trailing dots (fix for domains like "example.com.")
        domain = domain.rstrip('.')
        
        # Skip empty domains or localhost
        if not domain or domain in ['localhost', '127.0.0.1', '::1']:
            return None
            
        return domain
        
    except Exception as e:
        print(f"Warning: Could not parse '{url_or_domain}': {e}")
        return None


def clean_domains_file(input_file, output_file=None, verbose=True):
    """Read domains file, remove duplicates, sort, and save"""
    
    input_path = Path(input_file)
    if not input_path.exists():
        print(f"❌ Error: File '{input_file}' not found.")
        return None
    
    # Set output file if not provided
    if output_file is None:
        output_file = input_path.parent / f"{input_path.stem}_cleaned{input_path.suffix}"
    else:
        output_file = Path(output_file)
    
    if verbose:
        print(f"📖 Reading domains from: {input_file}")
    
    # Read and process the file
    domains = set()
    total_lines = 0
    processed_lines = 0
    skipped_lines = []
    
    try:
        with open(input_path, 'r', encoding='utf-8') as f:
            for line_num, line in enumerate(f, 1):
                total_lines += 1
                original_line = line.strip()
                
                # Extract domain from the line
                domain = extract_domain_from_url(line)
                
                if domain:
                    domains.add(domain)
                    processed_lines += 1
                elif original_line and not original_line.startswith('#'):
                    # Track non-empty, non-comment lines that couldn't be processed
                    skipped_lines.append((line_num, original_line))
    
    except Exception as e:
        print(f"❌ Error reading file: {e}")
        return None
    
    # Sort domains alphabetically
    sorted_domains = sorted(domains)
    
    # Save cleaned results
    try:
        # Create output directory if it doesn't exist
        output_file.parent.mkdir(parents=True, exist_ok=True)
        
        with open(output_file, 'w', encoding='utf-8') as f:
            f.write("# Cleaned and Sorted Domain List\n")
            f.write(f"# Original file: {input_file}\n")
            f.write(f"# Total lines processed: {total_lines}\n")
            f.write(f"# Valid domains found: {processed_lines}\n")
            f.write(f"# Unique domains after deduplication: {len(sorted_domains)}\n")
            f.write(f"# Duplicates removed: {processed_lines - len(sorted_domains)}\n")
            f.write("# Generated by clean_domains_advanced.py\n")
            f.write("\n")
            
            for domain in sorted_domains:
                f.write(f"{domain}\n")
        
        if verbose:
            print(f"\n✅ SUCCESS!")
            print(f"📊 Statistics:")
            print(f"   Total lines read: {total_lines:,}")
            print(f"   Valid domains found: {processed_lines:,}")
            print(f"   Unique domains after deduplication: {len(sorted_domains):,}")
            print(f"   Duplicates removed: {processed_lines - len(sorted_domains):,}")
            
            if skipped_lines:
                print(f"   Skipped lines (couldn't parse): {len(skipped_lines):,}")
                if len(skipped_lines) <= 5:
                    for line_num, content in skipped_lines:
                        print(f"     Line {line_num}: {content}")
                else:
                    print(f"     First 3 skipped lines:")
                    for line_num, content in skipped_lines[:3]:
                        print(f"     Line {line_num}: {content}")
                    print(f"     ... and {len(skipped_lines) - 3} more")
            
            print(f"💾 Cleaned domains saved to: {output_file}")
            
            # Show preview of cleaned domains
            if sorted_domains:
                print(f"\n📋 Preview of cleaned domains:")
                preview_count = min(10, len(sorted_domains))
                for i, domain in enumerate(sorted_domains[:preview_count], 1):
                    print(f"   {i:2d}. {domain}")
                
                if len(sorted_domains) > preview_count:
                    print(f"   ... and {len(sorted_domains) - preview_count} more domains")
    
    except Exception as e:
        print(f"❌ Error writing output file: {e}")
        return None
    
    return sorted_domains


def main():
    """Main function with command-line argument parsing"""
    parser = argparse.ArgumentParser(
        description="Clean domain list by removing duplicates and sorting",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python clean_domains_advanced.py domains.txt
  python clean_domains_advanced.py input.txt output.txt
  python clean_domains_advanced.py reports.txt --output cleaned_domains.txt
        """
    )
    
    parser.add_argument('input_file', 
                       help='Input file containing domains/URLs to clean')
    parser.add_argument('output_file', nargs='?',
                       help='Output file for cleaned domains (optional)')
    parser.add_argument('--output', '-o', 
                       help='Output file for cleaned domains (alternative to positional arg)')
    parser.add_argument('--quiet', '-q', action='store_true',
                       help='Suppress verbose output')
    
    args = parser.parse_args()
    
    # Determine output file
    output_file = args.output_file or args.output
    
    if not args.quiet:
        print("🧹 Advanced Domain List Cleaner")
        print("=" * 50)
    
    # Check if input file exists
    if not Path(args.input_file).exists():
        print(f"❌ Input file not found: {args.input_file}")
        sys.exit(1)
    
    # Clean the domains
    cleaned_domains = clean_domains_file(
        args.input_file, 
        output_file, 
        verbose=not args.quiet
    )
    
    if cleaned_domains is not None:
        if not args.quiet:
            print(f"\n🎉 Domain cleaning completed successfully!")
            print(f"📈 Result: {len(cleaned_domains)} unique domains")
        sys.exit(0)
    else:
        print(f"\n❌ Domain cleaning failed.")
        sys.exit(1)


if __name__ == "__main__":
    main() 