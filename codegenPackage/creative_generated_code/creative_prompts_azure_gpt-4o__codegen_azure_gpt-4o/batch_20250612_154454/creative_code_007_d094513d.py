"""
Models for the school management system.

- AcademicSchedule: Represents class schedules.
- CharacterTracking: Tracks character education details for students.
"""

from django.db import models

class AcademicSchedule(models.Model):
    class_name = models.CharField(max_length=100)
    subject = models.CharField(max_length=100)
    teacher = models.CharField(max_length=100)
    start_time = models.TimeField()
    end_time = models.TimeField()

    def __str__(self):
        return f"{self.class_name} - {self.subject} ({self.start_time} to {self.end_time})"

class CharacterTracking(models.Model):
    student_name = models.CharField(max_length=100)
    behavior_notes = models.TextField()
    date = models.DateField(auto_now_add=True)

    def __str__(self):
        return f"{self.student_name} - {self.date}"

