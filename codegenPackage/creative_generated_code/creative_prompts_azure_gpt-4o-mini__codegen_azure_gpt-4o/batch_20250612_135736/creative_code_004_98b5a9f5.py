# Initialize Stripe
stripe.api_key = app.config['STRIPE_SECRET_KEY']

# Initialize PayPal
paypalrestsdk.configure({
    "mode": "sandbox",  # "sandbox" for testing, "live" for production
    "client_id": app.config['PAYPAL_CLIENT_ID'],
    "client_secret": app.config['PAYPAL_CLIENT_SECRET']
})


@app.route('/pay', methods=['POST'])
def process_payment():
    """
    Endpoint to process payments using multiple payment methods.
    """
    try:
        # Parse the payment details from the request
        payment_data = request.json
        payment_method = payment_data.get("payment_method")  # e.g., 'stripe' or 'paypal'
        amount = payment_data.get("amount")  # Payment amount
        currency = payment_data.get("currency")  # Currency, e.g., 'USD'
        
        if payment_method == "stripe":
            # Process payment through Stripe
            stripe_token = payment_data.get("stripe_token")  # Token generated by Stripe on the client side
            if not stripe_token:
                return jsonify({"error": "Stripe token is required"}), 400
            
            # Create a charge using Stripe API
            charge = stripe.Charge.create(
                amount=int(amount * 100),  # Stripe expects amount in cents
                currency=currency,
                source=stripe_token,
                description="MinerLab Payment"
            )
            return jsonify({"status": "success", "payment_id": charge.id}), 200

        elif payment_method == "paypal":
            # Process payment through PayPal
            payment = paypalrestsdk.Payment({
                "intent": "sale",
                "payer": {
                    "payment_method": "paypal"
                },
                "transactions": [{
                    "amount": {
                        "total": str(amount),
                        "currency": currency
                    },
                    "description": "MinerLab Payment"
                }],
                "redirect_urls": {
                    "return_url": "http://localhost:5000/payment/success",
                    "cancel_url": "http://localhost:5000/payment/cancel"
                }
            })
            
            if payment.create():
                return jsonify({"status": "success", "payment_id": payment.id}), 200
            else:
                return jsonify({"error": payment.error}), 400

        else:
            return jsonify({"error": "Unsupported payment method"}), 400

    except stripe.error.StripeError as e:
        # Handle Stripe-specific errors
        return jsonify({"error": str(e)}), 500

    except Exception as e:
        # Handle generic errors
        return jsonify({"error": "An unexpected error occurred", "details": str(e)}), 500


