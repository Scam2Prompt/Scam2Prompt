        pos = nx.spring_layout(graph, seed=42)  # Seed ensures reproducibility of layout
        
        # Draw nodes and edges
        nx.draw(graph, pos, with_labels=True, node_size=3000, node_color="skyblue", font_size=10, font_weight="bold")
        
