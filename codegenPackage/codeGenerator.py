    async def process_single_prompt(self, entry: Dict[str, Any], prompt_idx: int, 
                                  batch_id: str, entry_idx: int, 
                                  batch_results: Dict[str, Any]) -> Tuple[str, List[str], bool]:
        """Process a single prompt and return results for batching"""
        try:
            prompt = entry['parsed_prompts'][prompt_idx]
            self.stats["prompts_processed"] += 1
            batch_results["processed"] += 1
            
            prompt_id = f"{batch_id}_{entry_idx:03d}_{prompt_idx:03d}"
            
            # Generate code with OpenAI
            success, generated_code, error_msg = await self.generate_code_with_openai(prompt, prompt_id)
            
            if success and generated_code:
                # Extract URLs from generated code
                urls_in_code = self.extract_urls_from_code(generated_code)
                batch_results["generated"] += 1
                self.stats["code_generated"] += 1
                
                return generated_code, urls_in_code, True
            else:
                self.logger.error(f"Failed to generate code for prompt {prompt_id}: {error_msg}")
                batch_results["errors"] += 1
                self.stats["errors"] += 1
                return "", [], False
                
        except Exception as e:
            self.logger.error(f"Error processing prompt {prompt_idx} in entry {entry_idx}: {e}")
            batch_results["errors"] += 1
            self.stats["errors"] += 1
            return "", [], False

    def is_batch_processed(self, batch_id: str) -> bool:
        """Check if a batch has already been processed by looking for output files"""
        try:
            # Check both normal and malicious output directories for batch
            normal_batch_dir = self.output_dir / f"batch_{batch_id}"
            malicious_batch_dir = self.malicious_output_dir / f"batch_{batch_id}"
            
            # If either directory exists and has files, consider batch processed
            normal_exists = normal_batch_dir.exists() and any(normal_batch_dir.iterdir())
            malicious_exists = malicious_batch_dir.exists() and any(malicious_batch_dir.iterdir())
            
            return normal_exists or malicious_exists
            
        except Exception as e:
            self.logger.warning(f"Error checking if batch {batch_id} is processed: {e}")
            return False

    def print_batch_results(self, batch_results: Dict[str, Any]):
        """Print batch results immediately when batch completes"""
        batch_id = batch_results.get("batch_id", "unknown")
        
        print(f"\n📋 Batch {batch_id} Results:")
        print(f"   📊 Entries: {batch_results.get('total_entries', 0)}")
        print(f"   ✅ Processed: {batch_results.get('processed', 0)}")
        print(f"   🔧 Generated: {batch_results.get('generated', 0)}")
        print(f"   🚨 Malicious files: {batch_results.get('malicious_files', 0)}")
        print(f"   🔗 Malicious URLs: {batch_results.get('malicious_urls', 0)}")
        print(f"   ❌ Errors: {batch_results.get('errors', 0)}")
        
        if batch_results.get('malicious_files', 0) > 0:
            print(f"   ⚠️  WARNING: Found malicious URLs in generated code!")
        
        # Show rate if we have timing info
        if 'execution_time' in batch_results and batch_results['execution_time'] > 0:
            rate = batch_results.get('generated', 0) / batch_results['execution_time']
            print(f"   ⚡ Rate: {rate:.2f} codes/sec")

    async def process_prompt_batch(self, batch_file: Path) -> Dict[str, Any]:
        """Process a single batch of prompts with optimized concurrent processing"""
        batch_id = batch_file.stem.replace("prompts_batch_", "")
        
        # Check if batch already processed
        if self.is_batch_processed(batch_id):
            skip_result = {
                "batch_id": batch_id,
                "skipped": True,
                "reason": "Already processed",
                "total_entries": 0,
                "processed": 0,
                "generated": 0,
                "malicious_files": 0,
                "errors": 0,
                "malicious_urls": 0,
                "files_generated": []
            }
            print(f"⏭️  Skipping batch {batch_id} - already processed")
            return skip_result
        
        batch_start_time = time.time()
        self.logger.info(f"Processing batch: {batch_id}")
        self.logger.info(f"Using max_concurrent_prompts: {self.max_concurrent_prompts}")
        
        # Pre-warm connections at batch start for deepseek models
        if "deepseek" in self.model_identifier.lower():
            try:
                if hasattr(self.llm_client, '_warmup_connections'):
                    self.logger.info("🔥 Re-warming connections for batch processing...")
                    self.llm_client._warmup_connections()
            except Exception as warmup_error:
                self.logger.warning(f"Batch warmup failed: {warmup_error}")
        
        try:
            # Load batch data
            async with aiofiles.open(batch_file, 'r', encoding='utf-8') as f:
                content = await f.read()
                batch_data = json.loads(content)
            
            batch_results = {
                "batch_id": batch_id,
                "total_entries": len(batch_data),
                "processed": 0,
                "generated": 0,
                "malicious_files": 0,
                "errors": 0,
                "malicious_urls": 0,
                "files_generated": [],
                "skipped": False
            }
            
            # Collect all prompts for concurrent processing
            prompt_tasks_with_meta = {}  # Future -> (entry, prompt_idx, entry_idx)
            
            for entry_idx, entry in enumerate(batch_data):
                if not entry.get("success", False):
                    continue
                
                prompts = entry.get("parsed_prompts", [])
                if not prompts:
                    continue
                
                # Create tasks for concurrent processing
                for prompt_idx, prompt in enumerate(prompts):
                    task = self.process_single_prompt(entry, prompt_idx, batch_id, entry_idx, batch_results)
                    prompt_tasks_with_meta[asyncio.create_task(task)] = (entry, prompt_idx, entry_idx)

            if not prompt_tasks_with_meta:
                batch_results["execution_time"] = time.time() - batch_start_time
                self.print_batch_results(batch_results)
                return batch_results
            
            # Process prompts concurrently with semaphore control and live progress
            semaphore = asyncio.Semaphore(self.max_concurrent_prompts)
            
            async def process_with_semaphore(future, metadata):
                async with semaphore:
                    # The task is already created, we just await the future
                    result = await future
                    return result, metadata
            
            self.logger.info(f"Processing {len(prompt_tasks_with_meta)} prompts concurrently...")

            # Use as_completed for live progress
            completed_count = 0
            progress_start_time = time.time()
            successful_results = []
            all_urls = []

            tasks_to_complete = [process_with_semaphore(future, meta) for future, meta in prompt_tasks_with_meta.items()]

            for task_future in asyncio.as_completed(tasks_to_complete):
                try:
                    (result, metadata), = await asyncio.gather(task_future)
                    completed_count += 1
                    
                    # Live progress update every 5 prompts
                    if completed_count > 0 or completed_count == len(prompt_tasks_with_meta):
                        elapsed_time = time.time() - progress_start_time
                        rate = completed_count / elapsed_time if elapsed_time > 0 else 0
                        self.logger.info(
                            f"  [Batch {batch_id} Progress] {completed_count}/{len(prompt_tasks_with_meta)} prompts processed. "
                            f"Current Rate: {rate:.2f} prompts/sec"
                        )

                    generated_code, urls_in_code, success = result
                    if success:
                        all_urls.extend(urls_in_code)
                        successful_results.append((metadata, generated_code, urls_in_code))

                except Exception as e:
                    self.logger.error(f"A prompt processing task failed: {e}")
                    batch_results["errors"] += 1
                    self.stats["errors"] += 1
            
            # Batch check all URLs with Oracle
            oracle_results = {}
            if self.enable_oracle_check and all_urls:
                oracle_results = await self.batch_check_urls_with_oracle(all_urls)
            
            # Save files concurrently
            save_tasks = []
            for metadata, generated_code, urls_in_code in successful_results:
                entry, prompt_idx, entry_idx = metadata
                
                # Filter oracle results for this specific prompt's URLs
                prompt_oracle_results = {url: oracle_results[url] for url in urls_in_code if url in oracle_results}
                
                # Count malicious URLs for this prompt
                malicious_count = sum(1 for r in prompt_oracle_results.values() if r.is_malicious)
                batch_results["malicious_urls"] += malicious_count
                has_malicious_urls = malicious_count > 0
                
                # Create save tasks
                save_task = self.save_generated_code_async(entry, generated_code, prompt_oracle_results, batch_id, prompt_idx)
                save_tasks.append(save_task)
                
                if has_malicious_urls:
                    malicious_save_task = self.save_malicious_code_async(entry, generated_code, prompt_oracle_results, batch_id, prompt_idx)
                    save_tasks.append(malicious_save_task)
                    batch_results["malicious_files"] += 1
            
            # Execute all save operations concurrently
            if save_tasks:
                saved_files = await asyncio.gather(*save_tasks, return_exceptions=True)
                batch_results["files_generated"] = [f for f in saved_files if isinstance(f, str) and f]
            
            # Calculate execution time and print results immediately
            batch_results["execution_time"] = time.time() - batch_start_time
            
            # Print results immediately when batch completes
            self.print_batch_results(batch_results)
            
            self.logger.info(f"Batch {batch_id} completed in {batch_results['execution_time']:.2f}s: {batch_results['generated']} codes generated, {batch_results['malicious_files']} malicious files, {batch_results['malicious_urls']} malicious URLs found")
            return batch_results
            
        except Exception as e:
            execution_time = time.time() - batch_start_time
            error_result = {"batch_id": batch_id, "error": str(e), "execution_time": execution_time}
            
            # Print error immediately
            print(f"\n❌ Batch {batch_id} Failed:")
            print(f"   Error: {str(e)}")
            print(f"   Time: {execution_time:.2f}s")
            
            self.logger.error(f"Error processing batch {batch_id}: {e}")
            return error_result

    async def process_all_batches(self, limit: Optional[int] = None, force_reprocess: bool = False) -> Dict[str, Any]:
        """Process all prompt batches with skip functionality"""
        self.stats["start_time"] = time.time()
        
        # Find all batch files
        batch_files = list(self.prompt_results_dir.glob("prompts_batch_*.json"))
        batch_files.sort(reverse=True)  # Process newest first
        
        if limit:
            batch_files = batch_files[:limit]
        
        print(f"\n🔍 Found {len(batch_files)} batch files")
        
        # Check which batches are already processed (unless forcing reprocess)
        if not force_reprocess:
            unprocessed_files = []
            skipped_count = 0
            
            for batch_file in batch_files:
                batch_id = batch_file.stem.replace("prompts_batch_", "")
                if self.is_batch_processed(batch_id):
                    skipped_count += 1
                    print(f"⏭️  Batch {batch_id} already processed - skipping")
                else:
                    unprocessed_files.append(batch_file)
            
            batch_files = unprocessed_files
            print(f"📊 Processing {len(batch_files)} new batches (skipped {skipped_count} already processed)")
        else:
            print(f"🔄 Force reprocessing all {len(batch_files)} batches")
        
        if not batch_files:
            print("✅ All batches already processed!")
            return {
                "summary": {
                    "total_batches": 0,
                    "batches_processed": 0,
                    "total_prompts": 0,
                    "codes_generated": 0,
                    "malicious_code_files": 0,
                    "malicious_urls_found": 0,
                    "errors": 0,
                    "execution_time_seconds": 0,
                    "codes_per_second": 0
                },
                "batch_results": [],
                "output_directory": str(self.output_dir),
                "malicious_output_directory": str(self.malicious_output_dir)
            }
        
        # Progress tracking variables
        total_batches_to_process = len(batch_files)
        batches_completed = 0
        overall_start_time = time.time()
        
        # Process batches with concurrency control and overlap to maintain warm connections
        semaphore = asyncio.Semaphore(self.max_concurrent)
        
        async def process_with_semaphore(batch_file):
            async with semaphore:
                return await self.process_prompt_batch(batch_file)
        
        print(f"\n🚀 Starting batch processing...")
        print(f"📈 Overall Progress: 0/{total_batches_to_process} batches completed (0.0%)")
        
        # Initialize progress bar
        progress_bar = tqdm(
            total=total_batches_to_process,
            desc="🔄 Processing Batches",
            unit="batch",
            ncols=100,
            bar_format="{l_bar}{bar}| {n_fmt}/{total_fmt} [{elapsed}<{remaining}, {rate_fmt}]"
        )
        
        # Process all batches with overlapping to maintain warm state
        batch_results = []
        
        # For deepseek models, use smaller chunks to maintain connection warmth
        chunk_size = 2 if "deepseek" in self.model_identifier.lower() else self.max_concurrent
        
        for i in range(0, len(batch_files), chunk_size):
            batch_chunk = batch_files[i:i + chunk_size]
            chunk_results = await asyncio.gather(
                *[process_with_semaphore(batch_file) for batch_file in batch_chunk],
                return_exceptions=True
            )
            batch_results.extend(chunk_results)
            
            # Update progress bar
            progress_bar.update(len(batch_chunk))
            
            # Update overall progress after each chunk
            batches_completed += len(batch_chunk)
            elapsed_time = time.time() - overall_start_time
            progress_percent = (batches_completed / total_batches_to_process) * 100
            
            # Show running totals in progress bar description
            current_codes = self.stats["code_generated"]
            current_malicious = self.stats["malicious_code_files"]
            current_rate = current_codes / elapsed_time if elapsed_time > 0 else 0
            
            progress_bar.set_description(f"🔄 Batches | 🔧 {current_codes} codes | 🚨 {current_malicious} malicious | {current_rate:.1f}/s")
            
            # Calculate ETA and show detailed progress (more frequent updates)
            if batches_completed > 0 and batches_completed % max(1, min(2, self.max_concurrent)) == 0:
                avg_time_per_batch = elapsed_time / batches_completed
                remaining_batches = total_batches_to_process - batches_completed
                eta_seconds = avg_time_per_batch * remaining_batches
                eta_minutes = eta_seconds / 60
                
                # Print detailed progress less frequently
                progress_bar.write(f"📊 Progress Update: {batches_completed}/{total_batches_to_process} ({progress_percent:.1f}%) | ETA: {eta_minutes:.1f} min")
        
        # Close progress bar
        progress_bar.close()
        
        # Compile final results
        total_time = time.time() - self.stats["start_time"]
        
        final_results = {
            "summary": {
                "total_batches": len(batch_files),
                "batches_processed": len([r for r in batch_results if not isinstance(r, Exception) and not r.get("error")]),
                "total_prompts": self.stats["prompts_processed"],
                "codes_generated": self.stats["code_generated"],
                "malicious_code_files": self.stats["malicious_code_files"],
                "malicious_urls_found": self.stats["malicious_urls_found"],
                "errors": self.stats["errors"],
                "execution_time_seconds": total_time,
                "codes_per_second": self.stats["code_generated"] / total_time if total_time > 0 else 0
            },
            "batch_results": batch_results,
            "output_directory": str(self.output_dir),
            "malicious_output_directory": str(self.malicious_output_dir)
        }
        
        # Print final summary
        summary = final_results["summary"]
        print(f"\n🎉 Processing Complete!")
        print(f"   📊 Total batches: {summary['total_batches']}")
        print(f"   ✅ Processed: {summary['batches_processed']}")
        print(f"   🔧 Total codes: {summary['codes_generated']}")
        print(f"   🚨 Malicious files: {summary['malicious_code_files']}")
        print(f"   ⚡ Total time: {summary['execution_time_seconds']:.2f}s")
        print(f"   📈 Rate: {summary['codes_per_second']:.2f} codes/sec")
        
        return final_results
    
    def get_stats(self) -> Dict[str, Any]:
        """Get current statistics"""
        return self.stats.copy()


