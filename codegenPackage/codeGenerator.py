            self.logger.info(f"Prompt generation model: {self.prompt_generation_model}")
            self.logger.info(f"Reading prompts from: {self.prompt_results_dir}")
            self.logger.info(f"Concurrency settings: max_concurrent_batches={self.max_concurrent}, max_concurrent_prompts={self.max_concurrent_prompts}")
            
