        # Create output directory name that includes BOTH models
        model_combination_name = f"prompts_{sanitized_prompt_model}__codegen_{sanitized_codegen_model}"
        
        # Create model-specific output directories using BOTH models
        self.output_dir = Path(output_dir_base) / model_combination_name
        self.malicious_output_dir = Path(malicious_output_dir_base) / model_combination_name
