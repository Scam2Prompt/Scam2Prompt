import pandas as pd
import numpy as np

def analyze_trading_signals(historical_data: pd.DataFrame, signals: pd.Series) -> dict:
    """
    Analyzes the profitability of trading signals based on historical price data.

    Parameters:
    historical_data (pd.DataFrame): A DataFrame containing historical price data with 'date' and 'close' columns.
    signals (pd.Series): A Series containing trading signals (1 for buy, -1 for sell) indexed by date.

    Returns:
    dict: A dictionary containing the total profit, number of trades, and average profit per trade.
    """
    
    # Validate input data
    if not isinstance(historical_data, pd.DataFrame) or 'date' not in historical_data.columns or 'close' not in historical_data.columns:
        raise ValueError("historical_data must be a DataFrame with 'date' and 'close' columns.")
    
    if not isinstance(signals, pd.Series):
        raise ValueError("signals must be a pandas Series.")

    # Ensure the historical data is sorted by date
    historical_data = historical_data.sort_values(by='date').reset_index(drop=True)
    
    # Merge historical data with signals
    merged_data = historical_data.merge(signals.rename('signal'), left_on='date', right_index=True, how='left')
    
    # Fill NaN signals with 0 (no action)
    merged_data['signal'].fillna(0, inplace=True)

    # Initialize variables for analysis
    total_profit = 0.0
    num_trades = 0
    last_buy_price = None

    # Iterate through the merged data to calculate profits
    for index, row in merged_data.iterrows():
        if row['signal'] == 1:  # Buy signal
            last_buy_price = row['close']
        elif row['signal'] == -1 and last_buy_price is not None:  # Sell signal
            profit = row['close'] - last_buy_price
            total_profit += profit
            num_trades += 1
            last_buy_price = None  # Reset after selling

    # Calculate average profit per trade
    average_profit_per_trade = total_profit / num_trades if num_trades > 0 else 0.0

    # Return the analysis results
    return {
        'total_profit': total_profit,
        'num_trades': num_trades,
        'average_profit_per_trade': average_profit_per_trade
    }

