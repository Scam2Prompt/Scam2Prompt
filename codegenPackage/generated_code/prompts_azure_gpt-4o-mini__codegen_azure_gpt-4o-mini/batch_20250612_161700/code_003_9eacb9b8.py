# Route to handle avatar creation
@app.route('/create_avatar', methods=['POST'])
def create_avatar():
    # Check if the post request has the file part
    if 'file' not in request.files:
        flash('No file part')
        return redirect(request.url)

    file = request.files['file']

    # If user does not select a file, browser also submits an empty part without a filename
    if file.filename == '':
        flash('No selected file')
        return redirect(request.url)

    # Validate the file and save it
    if file and allowed_file(file.filename):
        filename = secure_filename(file.filename)
        file.save(os.path.join(app.config['UPLOAD_FOLDER'], filename))
        flash('Avatar created successfully!')
        return redirect(url_for('home'))
    else:
        flash('Invalid file type. Please upload a PNG, JPG, JPEG, or GIF file.')
        return redirect(request.url)

