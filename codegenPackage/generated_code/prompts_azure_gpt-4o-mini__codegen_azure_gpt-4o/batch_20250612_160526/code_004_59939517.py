import pandas as pd

def analyze_trading_signals(price_data: pd.DataFrame, signals: pd.DataFrame) -> pd.DataFrame:
    """
    Analyzes the profitability of trading signals based on historical price data.

    Parameters:
        price_data (pd.DataFrame): A DataFrame containing historical price data with columns:
                                   'timestamp', 'price'.
        signals (pd.DataFrame): A DataFrame containing trading signals with columns:
                                'timestamp', 'signal' ('buy' or 'sell').

    Returns:
        pd.DataFrame: A DataFrame containing the analysis results with columns:
                      'timestamp', 'signal', 'price', 'profit_loss'.
    """
    # Validate input data
    if 'timestamp' not in price_data.columns or 'price' not in price_data.columns:
        raise ValueError("price_data must contain 'timestamp' and 'price' columns.")
    if 'timestamp' not in signals.columns or 'signal' not in signals.columns:
        raise ValueError("signals must contain 'timestamp' and 'signal' columns.")
    
    # Ensure data is sorted by timestamp
    price_data = price_data.sort_values(by='timestamp').reset_index(drop=True)
    signals = signals.sort_values(by='timestamp').reset_index(drop=True)
    
    # Merge price data with signals based on timestamp
    merged_data = pd.merge(signals, price_data, on='timestamp', how='inner')
    
    # Initialize variables for tracking profitability
    last_buy_price = None
    results = []

    # Iterate through merged data to calculate profit/loss
    for _, row in merged_data.iterrows():
        signal = row['signal']
        price = row['price']
        timestamp = row['timestamp']
        
        if signal == 'buy':
            # Record the buy price
            last_buy_price = price
            results.append({'timestamp': timestamp, 'signal': signal, 'price': price, 'profit_loss': None})
        elif signal == 'sell':
            if last_buy_price is not None:
                # Calculate profit/loss
                profit_loss = price - last_buy_price
                results.append({'timestamp': timestamp, 'signal': signal, 'price': price, 'profit_loss': profit_loss})
