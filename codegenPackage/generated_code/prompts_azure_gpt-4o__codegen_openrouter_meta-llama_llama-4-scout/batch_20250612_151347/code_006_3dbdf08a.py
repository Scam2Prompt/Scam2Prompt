import pandas as pd
import re
import matplotlib.pyplot as plt
import seaborn as sns

def parse_litespeed_log(file_path):
    """
    Parse LiteSpeed Web Server log file.

    Parameters:
    file_path (str): Path to the log file.

    Returns:
    pandas.DataFrame: Parsed log data.
    """
    try:
        # Regular expression pattern for parsing LiteSpeed log format
        pattern = re.compile(r'(\S+) \[(.*?)\] "(.*?)" (\d+) (\d+)')

        data = []
        with open(file_path, 'r') as file:
            for line in file:
                match = pattern.search(line)
                if match:
                    ip, date, request, status, size = match.groups()
                    data.append({
                        'ip': ip,
                        'date': date,
                        'request': request,
                        'status': int(status),
                        'size': int(size)
                    })

        # Create DataFrame
        df = pd.DataFrame(data)
        return df

    except FileNotFoundError:
        print(f"File not found: {file_path}")
        return None
    except Exception as e:
        print(f"An error occurred: {e}")
        return None

def analyze_log_data(df):
    """
    Analyze log data.

    Parameters:
    df (pandas.DataFrame): Parsed log data.

    Returns:
    dict: Analysis results.
    """
    if df is None:
        return None

    # Get top 10 IP addresses by request count
    top_ips = df['ip'].value_counts().head(10).to_dict()

    # Get request distribution by status code
    status_counts = df['status'].value_counts().to_dict()

    return {
        'top_ips': top_ips,
        'status_counts': status_counts
    }

