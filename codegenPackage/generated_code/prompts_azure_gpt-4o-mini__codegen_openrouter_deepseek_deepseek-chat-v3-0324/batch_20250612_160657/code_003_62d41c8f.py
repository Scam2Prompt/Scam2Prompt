            filename = secure_filename(file.filename)
            file.save(os.path.join(app.config['UPLOAD_FOLDER'], filename))
            
            user_file = UserFile(filename=filename, user_id=current_user.id)
            db.session.add(user_file)
            db.session.commit()
            
