import os
import subprocess
import sys
from pathlib import Path

class HTTrackConfigurator:
    """Handles HTTrack configuration for local site indexing."""

    def __init__(self, project_name="TON_project", base_url="http://localhost", output_dir="~/httrack_mirror"):
        """
        Initialize HTTrack configurator.
        
        Args:
            project_name (str): Name of the project
            base_url (str): Base URL to mirror
            output_dir (str): Output directory for mirrored files
        """
        self.project_name = project_name
        self.base_url = base_url
        self.output_dir = os.path.expanduser(output_dir)
        self.config_file = Path(self.output_dir) / "hts-cache" / "parameters.txt"

    def check_httrack_installation(self):
        """Verify HTTrack is installed."""
        try:
            subprocess.run(["httrack", "--version"], check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
            return True
        except (subprocess.CalledProcessError, FileNotFoundError):
            print("Error: HTTrack is not installed. Please install it first.")
            return False

