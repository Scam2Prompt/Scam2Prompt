def is_trivial_content(visible_text: str) -> Tuple[bool, str]:
    """
    Detect common trivial HTML content like domain parking, expired domains, etc.
    
    Args:
        visible_text: The visible text from the webpage
        
    Returns:
        Tuple of (is_trivial: bool, reason: str)
    """
    text_lower = visible_text.lower()
    
    # Domain parking patterns
    parking_patterns = [
        r"domain parking",
        r"sedo domain parking",
        r"this domain (?:has|is) expired",
        r"domain (?:has|is) expired",
        r"renew now",
        r"get a new domain",
        r"registered at namesilo",
        r"find out who owns any domain",
        r"whois tool",
        r"webpage was generated by the domain owner",
        r"sedo maintains no relationship",
        r"domain for sale",
        r"buy this domain",
        r"premium domain"
    ]
    
    # Error/placeholder pages
    error_patterns = [
        r"404 not found",
        r"page not found",
        r"under construction",
        r"coming soon",
        r"site not found",
        r"website not found",
        r"default web page",
        r"apache.*default page",
        r"nginx.*default page",
        r"iis.*default page",
        r"welcome to nginx",
        r"it works!.*apache"
    ]
    
    # Registrar/hosting default pages
    registrar_patterns = [
        r"godaddy.*parked",
        r"namecheap.*parked",
        r"bluehost.*coming soon",
        r"hostgator.*default",
        r"cpanel.*default",
        r"plesk.*default",
        r"cloudflare.*error"
    ]
    
    # CAPTCHA/Bot detection pages
    captcha_patterns = [
        r"please enter.*characters.*see",
        r"enter.*characters.*image",
        r"captcha",
        r"验证码",  # Chinese for verification code
        r"请输入.*字符",  # Chinese: please enter characters
        r"确认.*访问者.*自动程序",  # Chinese: confirm visitor not automated program
        r"cookie.*启用",  # Chinese: cookies enabled
        r"换一张图",  # Chinese: change image
        r"human verification",
        r"prove you.*human",
        r"robot.*verification",
        r"automated.*program",
        r"confirm.*not.*bot",
        r"security check",
        r"access.*blocked",
        r"suspicious.*activity",
        r"verify.*identity",
        r"anti.*bot",
        r"protection.*automated"
    ]
    
    # Check for very short content (likely error/placeholder)
    if len(visible_text.strip()) < 50:
        return True, "Very short content (likely error page)"
    
    # Check parking patterns
    for pattern in parking_patterns:
        if re.search(pattern, text_lower):
            return True, f"Domain parking/expired: {pattern}"
    
    # Check error patterns
    for pattern in error_patterns:
        if re.search(pattern, text_lower):
            return True, f"Error/placeholder page: {pattern}"
    
    # Check registrar patterns
    for pattern in registrar_patterns:
        if re.search(pattern, text_lower):
            return True, f"Registrar default page: {pattern}"
    
    # Check CAPTCHA/bot detection patterns
    for pattern in captcha_patterns:
        if re.search(pattern, text_lower):
            return True, f"CAPTCHA/bot detection page: {pattern}"
    
    # Check for excessive repetition (common in parking pages)
    words = text_lower.split()
    if len(words) > 20:
        word_counts = {}
        for word in words:
            if len(word) > 3:  # Only count meaningful words
                word_counts[word] = word_counts.get(word, 0) + 1
        
        # If any word appears more than 20% of the time, likely spam/parking
        max_count = max(word_counts.values()) if word_counts else 0
        if max_count > len(words) * 0.2:
            return True, "Excessive word repetition (likely spam/parking)"
    
    return False, "Normal content"

def load_scam_urls() -> List[str]:
    """Load all URLs from scam database files"""
    urls = []
    
    # Load eth-phishing-detect.json
    eth_file = os.path.join(SCAM_DATABASE_DIR, "eth-phishing-detect.json")
    if os.path.exists(eth_file):
        with open(eth_file, 'r') as f:
            data = json.load(f)
            urls.extend(data.get('whitelist', []))
            urls.extend(data.get('blacklist', []))
    
    # Load phishingfort-lists.json
    phishingfort_file = os.path.join(SCAM_DATABASE_DIR, "phishingfort-lists.json")
    if os.path.exists(phishingfort_file):
        with open(phishingfort_file, 'r') as f:
            data = json.load(f)
            for url in data:
                urls.append(url)

    return urls

def normalize_url(url: str) -> str:
    """Add https:// prefix if missing"""
    if not url.startswith(('http://', 'https://')):
        return f"https://{url}"
    return url

def extract_text_from_cached_urls() -> Dict[str, Dict]:
    """Main function: extract visible text from all cached URLs in scam database"""
    cache = OptimizedHTMLCache("static")
    urls = load_scam_urls()
    results = {}
    
    for url in urls:
        normalized_url = normalize_url(url)
        
        # Get cached content
        html_content = cache.get_cached_content(normalized_url)
        if html_content:
            try:
                print(f"Processing {normalized_url}")
                visible_text, links = extract_visible_text(html_content, normalized_url)
                
                # Check if content is trivial
                is_trivial, reason = is_trivial_content(visible_text)
                
                results[normalized_url] = {
                    'visible_text': visible_text,
                    'links': links,
                    'is_trivial': is_trivial,
                    'trivial_reason': reason
                }
                
                if is_trivial:
                    print(f"  -> TRIVIAL: {reason}")
                else:
                    print(f"  -> Normal content ({len(visible_text)} chars)")
                    print(visible_text)
                
            except Exception as e:
                results[normalized_url] = {'error': str(e)}
    
    return results

